// The render thread posts ImageBitmaps on "kisak-present". This page paints the newest one into
// #game once per animation frame. Frame rate for the F1 overlay arrives on "kisak-stats".
const present = { ctx: null, latest: null, frames: 0, shown: 0, lastT: performance.now(), lastShown: 0 };

// engine key codes (src/win32/win_wndproc.cpp virtualKeyConvert; mouse 200.., wheel 205 = down, 206 = up)
const KEYMAP = {
  Backspace: 127, Tab: 9, Enter: 13, NumpadEnter: 191, ShiftLeft: 160, ShiftRight: 160, ControlLeft: 159, ControlRight: 159,
  AltLeft: 158, AltRight: 158, Pause: 153, CapsLock: 151, Escape: 27, Space: 32, PageUp: 164, PageDown: 163, End: 166, Home: 165,
  ArrowLeft: 156, ArrowUp: 154, ArrowRight: 157, ArrowDown: 155, Insert: 161, Delete: 162, Backquote: 126, Minus: 45, Equal: 61,
  BracketLeft: 91, BracketRight: 93, Backslash: 92, Semicolon: 59, Quote: 39, Comma: 44, Period: 46, Slash: 47, IntlBackslash: 92,
  Numpad0: 192, Numpad1: 188, Numpad2: 189, Numpad3: 190, Numpad4: 185, Numpad5: 186, Numpad6: 187, Numpad7: 182, Numpad8: 183, Numpad9: 184,
  NumpadMultiply: 198, NumpadAdd: 196, NumpadSubtract: 195, NumpadDecimal: 193, NumpadDivide: 194, NumLock: 197,
};
for (let i = 0; i < 10; ++i) KEYMAP[`Digit${i}`] = 48 + i;
for (let i = 0; i < 26; ++i) KEYMAP[`Key${String.fromCharCode(65 + i)}`] = 97 + i;
for (let i = 1; i <= 12; ++i) KEYMAP[`F${i}`] = 166 + i;

const call = (fn, ...a) => { const m = state.mod; if (m && m[fn]) m[fn](...a); };
const locked = () => document.pointerLockElement === $("game");
$("warmup-cancel").addEventListener("click", () => {
  call("_Kisak_CancelShaderWarmup");
  $("warmup").hidden = true;
});
let lastEscape = 0;
const lookKeys = new Set();
let lookAt = performance.now(), lookRemainderX = 0, lookRemainderY = 0;
function clearAgentLook() { lookKeys.clear(); lookRemainderX = lookRemainderY = 0; }

function enterPlay() {
  document.body.classList.add("playing");
  const canvas = $("game");
  const [w, h] = state.res.split("x").map(Number);
  canvas.width = w;
  canvas.height = h;
  present.latest = null;

  present.ctx = canvas.getContext("bitmaprenderer");
  const ch = new BroadcastChannel("kisak-present-" + webSession);
  ch.onmessage = (ev) => {
    try {
      present.frames++;
      if (present.latest) present.latest.close();
      present.latest = ev.data.bmp;
    } catch (e) {
      if (ev.data?.bmp) ev.data.bmp.close();
      if (present.ready) Atomics.store(present.ready, 0, 1);
      log(`presentation: ${e.message}`, "err");
    }
  };
  const stats = new BroadcastChannel("kisak-stats-" + webSession);
  stats.onmessage = (ev) => {
    const d = ev.data || {};
    if (d.warmup) {
      const w = d.warmup;
      $("warmup").hidden = !w.active;
      $("warmup-progress").max = Math.max(1, w.total);
      $("warmup-progress").value = w.done;
      $("warmup-status").textContent = `${w.done} / ${w.total} shaders ready`;
      if (w.active && locked()) document.exitPointerLock();
      return;
    }
    const fps = d.dt ? (d.frames * 1000) / d.dt : 0;
    $("fps").textContent = `${fps.toFixed(0)} render fps (${d.copied || 0} copied, ${present.shown} shown)`;
  };
  const loop = () => {
    const now = performance.now();
    const dt = Math.min(50, now - lookAt);
    lookAt = now;
    if (cfg.agent && state.mod?._Kisak_WantsMouseCapture?.() && lookKeys.size) {
      lookRemainderX += ((lookKeys.has("ArrowRight") ? 1 : 0) - (lookKeys.has("ArrowLeft") ? 1 : 0)) * dt * 0.3;
      lookRemainderY += ((lookKeys.has("ArrowDown") ? 1 : 0) - (lookKeys.has("ArrowUp") ? 1 : 0)) * dt * 0.3;
      const x = Math.trunc(lookRemainderX), y = Math.trunc(lookRemainderY);
      if (x || y) call("_Kisak_MouseMove", x, y);
      lookRemainderX -= x; lookRemainderY -= y;
    } else clearAgentLook();
    if (present.latest && present.ctx) {
      const b = present.latest;
      present.latest = null;
      try {
        if (canvas.width !== b.width || canvas.height !== b.height) { canvas.width = b.width; canvas.height = b.height; }
        present.ctx.transferFromImageBitmap(b);
        present.shown++;
        if ((state.engine?.frontendReady || state.engine?.connection === 10) && state.menuFrame !== undefined && present.shown > state.menuFrame && document.body.classList.contains("booting")) {
          state.menuReady = true;
          mark("menuReady");
          document.body.classList.remove("booting");
          setStatus(`Playing (${state.res}). Create a private match from the game menus. F1 shows the debug page.`);
        }
      } catch (e) {
        b.close?.();
      } finally {
        if (present.ready) Atomics.store(present.ready, 0, 1);
      }
    }
    requestAnimationFrame(loop);
  };
  requestAnimationFrame(loop);

  // ---- keyboard
  const onKey = (e, down) => {
    if (cfg.agent && (lookKeys.has(e.code) || (state.mod?._Kisak_WantsMouseCapture?.() && e.code.startsWith("Arrow")))) {
      e.preventDefault();
      if (down) lookKeys.add(e.code); else lookKeys.delete(e.code);
      return;
    }
    if (e.code === "F11") {
      if (down) {
        e.preventDefault();
        if (document.fullscreenElement) document.exitFullscreen();
        else $("stage").requestFullscreen().catch(() => {});
      }
      return;
    }
    if (e.code === "F1" || e.code === "F2") return;
    const k = KEYMAP[e.code];
    if (k === undefined) return;
    e.preventDefault();
    if (e.repeat && down) {
      // The engine repeats keys itself (SE_KEY down events are not auto-repeated by Windows either); but text
      // fields want repeated characters, so only repeat the char event below.
    } else {
      call("_Kisak_Key", k, down ? 1 : 0);
    }
    if (down) {
      if (e.code === "Escape") lastEscape = performance.now();
      let c = 0;
      if (e.key.length === 1 && !e.ctrlKey && !e.metaKey) c = e.key.charCodeAt(0);
      else if (e.code === "Backspace") c = 8;
      else if (e.code === "Enter" || e.code === "NumpadEnter") c = 13;
      else if (e.code === "Tab") c = 9;
      if (c) call("_Kisak_Char", c);
    }
  };
  // F1/F2 are page keys. They must work while the console input is focused, or the log cannot be closed.
  const onPageKey = (e) => {
    if (!state.play || e.repeat) return;
    if (e.code === "F1") {
      e.preventDefault();
      e.stopPropagation();
      const on = document.body.classList.toggle("debug");
      if (!on) {
        document.body.classList.remove("logshown");
        if (document.activeElement?.id === "cmd") $("game").focus();
      }
    } else if (e.code === "F2") {
      e.preventDefault();
      e.stopPropagation();
      if (!document.body.classList.contains("debug")) document.body.classList.add("debug");
      const shown = document.body.classList.toggle("logshown");
      if (!shown && document.activeElement?.id === "cmd") $("game").focus();
    }
  };
  window.addEventListener("pointerdown", () => { if (state.play) unlockAudio(); }, true);
  window.addEventListener("keydown", () => { if (state.play) unlockAudio(); }, true);
  window.addEventListener("keydown", onPageKey, true);
  window.addEventListener("keydown", (e) => { if (state.play && document.activeElement?.id !== "cmd") onKey(e, true); }, true);
  window.addEventListener("keyup", (e) => { if (state.play && document.activeElement?.id !== "cmd") onKey(e, false); }, true);

  // ---- mouse
  const toCanvas = (e) => {
    const r = canvas.getBoundingClientRect();
    // object-fit: contain letterboxes; map through the displayed content box
    const scale = Math.min(r.width / canvas.width, r.height / canvas.height);
    const cw = canvas.width * scale, chh = canvas.height * scale;
    const ox = r.left + (r.width - cw) / 2, oy = r.top + (r.height - chh) / 2;
    return [Math.max(0, Math.min(canvas.width - 1, Math.round((e.clientX - ox) / scale))),
            Math.max(0, Math.min(canvas.height - 1, Math.round((e.clientY - oy) / scale)))];
  };
  canvas.addEventListener("mousemove", (e) => {
    if (locked()) {
      call("_Kisak_MouseMove", Math.round(e.movementX), Math.round(e.movementY));
    } else {
      const [x, y] = toCanvas(e);
      call("_Kisak_MousePos", x, y);
    }
  });
  const btn = (e, down) => {
    if (down) unlockAudio();
    e.preventDefault();
    canvas.focus();
    const wants = state.mod?._Kisak_WantsMouseCapture ? state.mod._Kisak_WantsMouseCapture() : 0;
    // Position first, so a menu click lands even when it is also the click that arrived.
    if (!locked()) { const [x, y] = toCanvas(e); call("_Kisak_MousePos", x, y); }
    // In-game look capture consumes the click. Menu clicks (the engine does not want capture) go through.
    if (down && wants && !locked() && !cfg.agent) {
      const p = canvas.requestPointerLock({ unadjustedMovement: true });
      if (p && p.catch) p.catch(() => canvas.requestPointerLock());
      return;
    }
    const map = [200, 202, 201, 203, 204]; // DOM buttons: 0 left, 1 middle, 2 right, 3 back, 4 forward
    const k = map[e.button];
    if (k === undefined) return;
    call("_Kisak_Key", k, down ? 1 : 0);
  };
  const pressedCanvasButtons = new Set();
  canvas.addEventListener("mousedown", (e) => { pressedCanvasButtons.add(e.button); btn(e, true); });
  window.addEventListener("mouseup", (e) => {
    // Release a game press even outside the canvas, but do not steal focus or
    // cancel clicks on console inputs and loading-overlay controls.
    if (state.play && pressedCanvasButtons.delete(e.button)) btn(e, false);
  });
  canvas.addEventListener("contextmenu", (e) => e.preventDefault());
  canvas.addEventListener("wheel", (e) => {
    e.preventDefault();
    const k = e.deltaY > 0 ? 205 : 206;
    call("_Kisak_Key", k, 1);
    call("_Kisak_Key", k, 0);
  }, { passive: false });

  // Esc releases pointer lock without delivering a keydown: open the engine menu ourselves.
  document.addEventListener("pointerlockchange", () => {
    if (!locked() && performance.now() - lastEscape > 150) {
      const wants = state.mod?._Kisak_WantsMouseCapture ? state.mod._Kisak_WantsMouseCapture() : 0;
      if (wants) { call("_Kisak_Key", 27, 1); call("_Kisak_Key", 27, 0); }
    }
  });
  window.addEventListener("blur", () => { clearAgentLook(); pressedCanvasButtons.clear(); call("_Kisak_Focus", 0); });
  window.addEventListener("focus", () => call("_Kisak_Focus", 1));
  document.addEventListener("visibilitychange", () => { if (document.hidden) clearAgentLook(); call("_Kisak_Focus", document.hidden ? 0 : 1); });

  $("btn-log").onclick = () => {
    const shown = document.body.classList.toggle("logshown");
    if (shown) document.body.classList.add("debug");
    if (!shown && document.activeElement?.id === "cmd") $("game").focus();
  };
  $("btn-full").onclick = () => (document.fullscreenElement ? document.exitFullscreen() : $("stage").requestFullscreen());
  warnSoftwareGl();
  startRelay();
}

function warnSoftwareGl() {
  const canvas = document.createElement("canvas");
  const gl = canvas.getContext("webgl2");
  if (!gl) return;
  const ext = gl.getExtension("WEBGL_debug_renderer_info");
  const renderer = ext ? gl.getParameter(ext.UNMASKED_RENDERER_WEBGL) : gl.getParameter(gl.RENDERER);
  const soft = /swiftshader|llvmpipe|software|basic render|microsoft basic/i.test(renderer || "");
  const el = $("gpu");
  if (!el) return;
  if (soft) {
    el.hidden = false;
    el.textContent = `Software WebGL (${renderer}). Chrome: Settings, System, Use hardware acceleration when available, then relaunch. Confirm chrome://gpu says WebGL2: Hardware accelerated.`;
  } else {
    el.hidden = true;
  }
  log(`WebGL: ${renderer}`);
}

// Shared game transport: RTC datagrams with relay fallback. Host creates a room; ?join=ROOM joins it.
function startRelay() {
  if (state.relay) return;
  const inbox = [];
  let stopped = false;
  let iceServers = [];
  try { iceServers = JSON.parse(params.get("ice") || "[]"); }
  catch { log("network: invalid ice configuration", "err"); }
  const transport = new GameTransport({
    url: (location.protocol === "https:" ? "wss://" : "ws://") + location.host + "/relay",
    room: cfg.join, iceServers, rtc: params.get("net") !== "relay", log,
    failed: (message) => {
      setStatus(message);
      $("room").textContent = message;
      saveDiagnostics();
    },
    receive: (packet) => {
      if (!stopped && packet.length >= 7 && packet.length <= 4102 && inbox.length < 256) {
        inbox.push(packet);
        pump();
      }
    },
    ready: (room) => {
      state.relay.room = room;
      const link = new URL(location.href);
      link.searchParams.set("join", room);
      const note = $("room");
      if (note) note.textContent = `Room ${room} — join: ${link.href}`;
      log(`network: room ${room} (${cfg.join ? "guest" : "host"})`);
      if (!state.play) log(`Join link: ${link.href}`);
    },
  });
  state.relay = { transport, room: cfg.join || "" };
  let scratch = 0;
  function pump() {
    if (stopped) return;
    const mod = state.mod;
    if (!mod?._Kisak_NetPush || !mod?._Kisak_NetDrain) return;
    if (!scratch) scratch = mod._malloc(4102);
    if (!scratch) return;
    while (inbox.length) {
      const u = inbox.shift();
      mod.HEAPU8.set(u.subarray(6), scratch);
      mod._Kisak_NetPush(u[0], u[1], u[2], u[3], u[4] | (u[5] << 8), scratch, u.length - 6);
    }
    for (let i = 0; i < 256; ++i) {
      const n = mod._Kisak_NetDrain(scratch, 4102);
      if (n <= 6) break;
      transport.send(mod.HEAPU8.slice(scratch, scratch + n));
    }
  }
  state.relay.pump = pump;
  // Packet arrivals and the engine's async notification drive normal traffic.
  // This low-frequency fallback also drains packets queued during module startup.
  const timer = setInterval(pump, 50);
  const stop = () => {
    if (stopped) return;
    stopped = true;
    clearInterval(timer);
    inbox.length = 0;
    transport.close();
    if (scratch && state.mod) state.mod._free(scratch);
    scratch = 0;
  };
  state.relay.stop = stop;
  window.addEventListener("pagehide", stop, { once: true });
}

