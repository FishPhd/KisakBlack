// A pthread trap arrives on the page as an ErrorEvent whose error is null. Logging that event
// walks srcElement and prints the Window. These four fields are the whole page-side record.
function reportCrash(message, filename, lineno, colno) {
  const msg = message == null ? "" : String(message);
  const file = filename == null ? "" : String(filename);
  const lineNo = lineno == null ? "" : String(lineno);
  const col = colno == null ? "" : String(colno);
  log(`crash: ${msg} ${file}:${lineNo}:${col}`, "err");
}
