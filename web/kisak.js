  const renderer = ext ? gl.getParameter(ext.UNMASKED_RENDERER_WEBGL) : gl.getParameter(gl.RENDERER);
  state.renderer = renderer;
  const soft = /swiftshader|llvmpipe|software|basic render|microsoft basic/i.test(renderer || "");
  const el = $("gpu");
  if (!el) return;
