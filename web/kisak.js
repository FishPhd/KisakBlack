// ---------------------------------------------------------------- OPFS

async function dirHandle(parts, create) {
  let d = state.opfs;
  for (const p of parts) d = await d.getDirectoryHandle(p, { create });
  return d;
}

// The engine mounts OPFS through WasmFS' case-insensitive backend. That backend looks names up in the
// underlying file system *lower-cased* (it only keeps the original case for names it created itself),
// so everything the page writes under game/ must already be lower case: zone/Common/x.ff is stored as
// game/zone/common/x.ff. The engine's own spelling (zone\english\...) then resolves either way.
const opfsParts = (rel) => ["game", ...rel.toLowerCase().split("/")];

async function opfsSize(rel) {
  const parts = opfsParts(rel);
  const name = parts.pop();
  try {
    const d = await dirHandle(parts, false);
    return (await (await d.getFileHandle(name)).getFile()).size;
  } catch {
    return -1;
  }
}

async function readRootText(name) {
  try { return await (await (await state.opfs.getFileHandle(name)).getFile()).text(); } catch { return null; }
}

async function writeRootText(name, text) {
  const w = await (await state.opfs.getFileHandle(name, { create: true })).createWritable();
  await w.write(text);
  await w.close();
}

// ---------------------------------------------------------------- sources

async function childCI(dir, name) {
  for await (const [n, h] of dir.entries()) if (n.toLowerCase() === name.toLowerCase()) return h;
  throw new Error(`"${name}" not found in the chosen folder`);
}

async function openSource(entry) {
  const base = entry.path.split("/").map(encodeURIComponent);
  if (entry.gen) {
    const r = await fetch(cfg.gen + base[base.length - 1]);
    if (!r.ok) throw new Error(`${entry.path}: HTTP ${r.status} from ${cfg.gen}`);
    return r.body;
  }
  if (state.folder) {
    let d = state.folder;
    const parts = entry.path.split("/");
    const name = parts.pop();
    for (const p of parts) d = await childCI(d, p);
    return (await (await childCI(d, name)).getFile()).stream();
  }
  const r = await fetch(cfg.assets + base.join("/"));
  if (!r.ok) throw new Error(`${entry.path}: HTTP ${r.status} from ${cfg.assets}`);
  return r.body;
}

// ---------------------------------------------------------------- transfer

let progress = { total: 0, done: 0, label: "" };
// ui=false is for background prefetch: it counts toward "transferred" but never drives the progress bar.
function bump(n, ui) {
  state.transferred += n;
  if (!ui) return;
  progress.done += n;
  setBar(progress.total ? progress.done / progress.total : 0);
  setStatus(`${progress.label}  ${mb(progress.done)} / ${mb(progress.total)} MB`);
}

async function copyEntry(entry, ui) {
  const stream = await openSource(entry);
  const parts = opfsParts(entry.path);
  const name = parts.pop();
  const dir = await dirHandle(parts, true);
  // Bytes commit on close, but creating a new destination exposes an empty file.
  // The engine checks the manifest size before opening a prefetched fastfile.
  const w = await (await dir.getFileHandle(name, { create: true })).createWritable();
  const reader = stream.getReader();
  let written = 0;
  try {
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      await w.write(value);
      written += value.length;
      bump(value.length, ui);
    }
    if (written !== entry.size) throw new Error(`${entry.path}: got ${written} bytes, expected ${entry.size}`);
    await w.close();
  } catch (e) {
    await w.abort().catch(() => {});
    throw e;
  }
}

const inflight = new Map();

// Chrome will not start audio until resume() runs inside a user gesture. The engine
// creates the context while the page is booting (no gesture), queues menu sounds on it,
// and those nodes only become audible if that same context is resumed. Replacing a
// suspended context drops every sound already started on it.
function unlockAudio() {
  const Ctx = window.AudioContext || window.webkitAudioContext;
  if (!Ctx) return;
  let ctx = window.kisakAudio || state.mod?.kisakAudio;
  if (!ctx || ctx.state === "closed") {
    try { ctx = new Ctx(); } catch (e) { return; }
  }
  window.kisakAudio = ctx;
  if (state.mod) state.mod.kisakAudio = ctx;
  if (ctx.state === "running") return;
  const pending = ctx.resume();
  if (pending && pending.then) {
    pending.then(() => {
      if (ctx.state === "running" && !state.audioOn) {
        state.audioOn = true;
        log("audio: unmuted");
      }
    }).catch(() => {});
  }
}

function ensureEntry(entry, ui = true) {
  const key = entry.path.toLowerCase();
  let p = inflight.get(key);
  if (!p) {
    p = (async () => {
      if ((await opfsSize(entry.path)) === entry.size) return;
      await copyEntry(entry, ui);
    })();
    inflight.set(key, p);
    p.catch(() => inflight.delete(key));
  }
  return p;
}

async function importSet(entries, label) {
  const missing = [];
  for (const e of entries) if ((await opfsSize(e.path)) !== e.size) missing.push(e);
  if (!missing.length) return 0;
  progress = { total: missing.reduce((a, e) => a + e.size, 0), done: 0, label };
  log(`${label}: ${missing.length} file(s), ${mb(progress.total)} MB`);
  let next = 0;
  const worker = async () => {
    while (next < missing.length) await ensureEntry(missing[next++]);
  };
  await Promise.all([worker(), worker(), worker(), worker(), worker(), worker()]);
  setBar(1);
  return progress.total;
}

// ---------------------------------------------------------------- manifest

async function loadManifest() {
  // The server's copy wins (it may have gained a client set or new maps); the OPFS copy is the offline fallback.
  let text = null;
  try {
    // ?refresh forces a full download. Otherwise revalidate the stored copy with the server ETag
    // (Cache-Control: no-cache still stores the body; no-store would fetch it on every boot).
    const r = await fetch(cfg.gen + "manifest.json", { cache: cfg.refresh ? "reload" : "no-cache" });
    if (r.ok) {
      text = await r.text();
      await writeRootText("manifest.json", text);
    } else if (!(await readRootText("manifest.json"))) {
      throw new Error(`manifest.json: HTTP ${r.status} from ${cfg.gen} (run tools/web/gen_manifest.py)`);
    }
  } catch (e) {
    if (!(await readRootText("manifest.json"))) throw e;
  }
  if (!text) {
    text = await readRootText("manifest.json");
    log("manifest: server unreachable, using the copy cached in OPFS");
  }
  const m = JSON.parse(text);
  state.byKey.clear();
  const c = m.client || { boot: [], maps: {} };
  for (const e of [...m.boot, ...c.boot, ...Object.values(m.maps).flat(), ...Object.values(c.maps).flat()]) state.byKey.set(e.path.toLowerCase(), e);
  return m;
}

// The engine reads this to know which files it may ask for (Web_RemoteKnown / Web_EnsureFile).
async function writeManifestTxt(m) {
  const c = m.client || { boot: [], maps: {} };
  const seen = new Set();
  let t = "";
  const add = (e, map) => {
    const k = e.path.toLowerCase();
    if (seen.has(k)) return;
    seen.add(k);
    t += `${e.path}\t${e.size}\t${map}\n`;
  };
  for (const e of m.boot) add(e, "");
  for (const e of c.boot) add(e, "");
  for (const [map, es] of Object.entries(m.maps)) for (const e of es) add(e, map);
  for (const [map, es] of Object.entries(c.maps)) for (const e of es) add(e, map);
  await writeRootText("manifest.txt", t);
}

// ---------------------------------------------------------------- engine hooks

// Called by the engine's database thread (via the main thread) when it is about to open a fastfile
// that is not in OPFS yet. Resolves when the file is complete; the engine thread is blocked until then.
// A file the trimmed packs don't contain (menu art, most images). The dev server reads it out of
// the install's real IWDs. Written under game/ so the engine's "main/" search path finds it.
function kisakEnsureLoose(rel) {
  const key = rel.toLowerCase();
  const pack = key.startsWith("main/") ? key.slice(5) : key;
  let p = inflight.get("loose:" + key);
  if (!p) {
    p = (async () => {
      if ((await opfsSize(key)) > 0) return;
      const r = await fetch(new URL("pack/" + pack.split("/").map(encodeURIComponent).join("/"), location.href));
      if (!r.ok) throw new Error(`${pack}: HTTP ${r.status}`);
      const parts = opfsParts(key);
      const name = parts.pop();
      const dir = await dirHandle(parts, true);
      const w = await (await dir.getFileHandle(name, { create: true })).createWritable();
      try {
        await w.write(await r.arrayBuffer());
        await w.close();
      } catch (e) {
        await w.abort().catch(() => {});
        throw e;
      }
    })();
    inflight.set("loose:" + key, p);
    p.catch(() => inflight.delete("loose:" + key));
  }
  return p;
}

// Background ensure used when several zones are queued: start them together, do not drive the bar.
function kisakEnsureEntry(relLower) {
  const e = state.byKey.get(String(relLower || "").toLowerCase());
  if (!e) return Promise.resolve();
  return ensureEntry(e, false);
}

function kisakEnsureFile(relLower) {
  const e = state.byKey.get(relLower);
  if (!e) return Promise.reject(new Error(`not in manifest: ${relLower}`));
  progress = { total: e.size, done: 0, label: `Loading ${e.path}` };
  const t0 = performance.now();
  return ensureEntry(e).then(() => {
    setBar(1);
    setStatus(`${e.path} ready (${mb(e.size)} MB, ${((performance.now() - t0) / 1000).toFixed(1)} s)`);
  });
}

// Next map in the rotation: start copying its files now so the map change finds them local.
function kisakPrefetchMap(map) {
  const key = map.toLowerCase();
  const files = [...((state.manifest?.maps || {})[key] || []), ...((state.manifest?.client?.maps || {})[key] || [])];
  if (!files.length) return;
  log(`prefetch: ${map} (${files.length} file(s))`);
  for (const e of files) ensureEntry(e, false).catch((err) => log(`prefetch ${e.path}: ${err.message}`, "err"));
}

