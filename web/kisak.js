// Page shell for the KisakBlack browser dedicated server.
//
//  1. Imports the game files the server needs into OPFS (origin private file system), once.
//       boot set  : common_mp, code_*, patch_mp, localized pairs, iw_web.iwd, ...  (~59 MB)
//       per map   : the map's own fastfile (~36 MB), fetched the first time it is played, and
//                   prefetched when it is next in the rotation ("maps on demand"), or all up front
//                   ("everything now").
//     Files come from the game folder you pick (File System Access API, Chromium) or from
//     ?assets=<url> (tools/web/serve.mjs serves a game directory that way). iw_web.iwd and the
//     localized stubs are generated by tools/web/gen_manifest.py and come from ?gen=<url>.
//  2. Starts the engine (kisak.mjs / kisak.wasm) and bridges its console.
//
// A second launch finds every needed file in OPFS (size-checked) and the manifest cached there, so it
// transfers nothing but the engine itself.
//
// URL parameters: gen, assets, mode=lazy|bulk, args="<engine command line>", autostart, bots=<n>,
// refresh (force a full manifest download; otherwise the boot revalidates with the server ETag).

